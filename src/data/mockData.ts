function computeRiskLevel(index: number): RiskLevel {
  if (index >= 72) return 'critical';
  if (index >= 52) return 'high';
  if (index >= 30) return 'moderate';
  return 'low';
}

export const INITIAL_VILLAGES: Village[] = MEDICAL_CLUSTERS.flatMap((cluster, cIdx) => {
  return [0, 1, 2, 3].map((vSubIdx) => {
    const globalIdx = cIdx * 4 + vSubIdx;
    const offset = OFFSETS[vSubIdx];
    // Deterministic variation so every hackathon demo sees balanced realistic data
    const riskIndex = 18 + ((globalIdx * 17 + cIdx * 9) % 72);
    const population = 420 + ((globalIdx * 283) % 2750);
    const activePatientsCount = Math.round(population * (0.04 + (riskIndex / 100) * 0.06));
    const screenedLast30d = Math.round(activePatientsCount * (0.45 + ((globalIdx % 5) * 0.1)));
    const lastDay = 1 + ((globalIdx * 3) % 14);
    const nextDay = 20 + ((globalIdx * 2) % 9);

    return {
      id: `V-${String(globalIdx + 1).padStart(2, '0')}`,
      name: VILLAGE_NAMES[globalIdx],
      clusterId: cluster.id,
      lat: Number((cluster.lat + offset.dLat + ((globalIdx % 3) - 1) * 0.04).toFixed(4)),
      lng: Number((cluster.lng + offset.dLng + ((cIdx % 3) - 1) * 0.05).toFixed(4)),
      population,
      distanceToHubKm: offset.dist + ((globalIdx * 5) % 14),
      riskIndex,
      riskLevel: computeRiskLevel(riskIndex),
      rapidLabEquipped: vSubIdx % 2 === 0 || riskIndex >= 60,
      lastMedMobileVisit: `2026-11-${String(lastDay).padStart(2, '0')}`,
      nextMedMobileVisit: `2026-11-${String(nextDay).padStart(2, '0')}`,
      activePatientsCount,
      screenedLast30d,
      dominantConcern: CONCERNS[globalIdx % CONCERNS.length],
    };
  });
});

